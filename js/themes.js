const themePaletteKeys = [
	"background-0",
	"background-1",
	"background-2",
	"borders",
	"text-0",
	"text-1",
	"text-2",
	"links",
	"sidebar",
	"sidebar-text",
];
for (const theme of themes) {
	theme.originalPreset = theme.exports.dark_preset;
	const rows = themeModeColors[theme.title.split(" by ")[0]];
	theme.modePalettes = rows.map((row) => {
		const palette = Object.fromEntries(
			themePaletteKeys.map((key, index) => [key, row[index]]),
		);
		// Retain each sidebar image and its placement; only theme its overlay.
		if (/url\(/i.test(theme.originalPreset.sidebar)) {
			palette.sidebar = theme.originalPreset.sidebar
				.split(/(url\([^)]*\))/gi)
				.map((part) =>
					/^url\(/i.test(part)
						? part
						: part.replace(
								/#[a-f\d]{8}\b|#[a-f\d]{6}\b|#[a-f\d]{3}\b/gi,
								(hex) =>
									palette.sidebar + (hex.length === 9 ? hex.slice(7) : ""),
							),
				)
				.join("");
		}
		return palette;
	});
	theme.exports.dark_preset = theme.modePalettes[1];
}

function resolveThemeModePalette(preset, dark) {
	const theme = themes.find((theme) =>
		[theme.originalPreset, ...theme.modePalettes].some((candidate) =>
			themePaletteKeys.every(
				(key) => preset[key]?.toLowerCase() === candidate[key]?.toLowerCase(),
			),
		),
	);
	return theme ? { ...theme.modePalettes[dark ? 1 : 0] } : null;
}
